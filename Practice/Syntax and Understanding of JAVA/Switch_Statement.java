public class Switch_Statement
{
    public static void main (String [] args )
    {
        int dayNumber = 2;
        switch (dayNumber) {
            case 1:
                System.out.println("Monday");
                break;
            case 2:
                System.out.println("Tuesday");
                break;
            case 3 :
                System.out.println("Wednesday");
                break;
            case 4 :
                System.out.println("Thursday");
                break;            
        }
    }
}

// Output: Tuesday