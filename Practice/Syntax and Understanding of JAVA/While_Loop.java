public class While_Loop
{
    public static void main (String [] args)
    {
        int num = 1;
        while (num<=5) {
            System.out.println(num);
            num++;
        }

        int module = 4;
        while (module >= 1) {
            System.out.println("Module Left = " + module);
            module--;
        }
    }
}